const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const root = path.resolve(__dirname, '..');
const scanRoots = ['assets/img/full', 'assets/img/extra/full', 'assets/media'];
const supported = new Set(['.avif', '.gif', '.jpeg', '.jpg', '.mp4', '.pdf', '.png', '.webp']);
const output = path.join(root, 'assets/js/media-hashes.js');

function filesUnder(directory) {
  if (!fs.existsSync(directory)) return [];
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) return filesUnder(absolute);
    return supported.has(path.extname(entry.name).toLowerCase()) ? [absolute] : [];
  });
}

function hashFile(file) {
  return new Promise((resolve, reject) => {
    const hash = crypto.createHash('sha256');
    const stream = fs.createReadStream(file);
    stream.on('data', chunk => hash.update(chunk));
    stream.on('error', reject);
    stream.on('end', () => resolve(hash.digest('hex')));
  });
}

async function main() {
  const hashes = {};
  const byHash = new Map();
  for (const file of scanRoots.flatMap(dir => filesUnder(path.join(root, dir))).sort()) {
    const hash = await hashFile(file);
    const key = path.relative(root, file).split(path.sep).join('/');
    hashes[key] = hash;
    if (!byHash.has(hash)) byHash.set(hash, []);
    byHash.get(hash).push(key);
  }

  const content = `// Generated by scripts/generate-media-hashes.cjs. Do not edit by hand.\n` +
    `globalThis.MEDIA_HASHES = Object.freeze(${JSON.stringify(hashes, null, 2)});\n`;
  fs.writeFileSync(output, content, 'utf8');
  const duplicates = [...byHash.values()].filter(group => group.length > 1);
  console.log(`Hashed ${Object.keys(hashes).length} media files.`);
  console.log(`Found ${duplicates.length} exact duplicate content groups.`);
  for (const group of duplicates) console.log(`SHA-256 duplicate: ${group.join(' | ')}`);
}

main().catch(error => {
  console.error(error);
  process.exitCode = 1;
});
